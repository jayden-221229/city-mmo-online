const assert = require('assert');
const fs = require('fs');
const path = require('path');
const pkg = require('../package.json');
const config = require('../vercel.json');
const game = fs.readFileSync(path.join(__dirname, '../assets/js/game.js'), 'utf8');
const index = fs.readFileSync(path.join(__dirname, '../index.html'), 'utf8');
const api = fs.readFileSync(path.join(__dirname, '../api/[...path].js'), 'utf8');
assert(pkg.dependencies['@socket.io/redis-adapter'], 'Redis adapter dependency exists');
assert(pkg.dependencies.ioredis, 'ioredis dependency exists');
assert(config.functions['api/**/*.js'].maxDuration === 60, 'Vercel Hobby WebSocket function stays within the 60-second limit');
assert(fs.existsSync(path.join(__dirname, '../api/[...path].js')), 'catch-all API function receives nested Socket.IO and auth routes');
assert(game.includes("transports: ['websocket']"), 'client forces WebSocket transport to avoid cross-instance polling sessions');
assert(index.includes("'/api/socket-io/socket.io'"), 'HTML loads Socket.IO from the Vercel function path');
assert(api.includes('ACQUIRE_WORLD_LUA') && api.includes('SAVE_AND_UNLOCK_LUA'), 'world mutations use a shared Redis lease and atomic persisted commit');
assert(api.includes('createAdapter(redisPubClient, redisSubClient'), 'Socket.IO broadcasts use Redis adapter across Vercel instances');
console.log('Vercel/Upstash deployment configuration checks passed');
